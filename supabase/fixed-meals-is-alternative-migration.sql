-- Beneficiary Fixed Meals — علامة "صنف بديل"
--
-- المشكلة: بعض المستفيدين مستبعدين كل أصناف المنيو، فصارت أصنافهم الثابتة
-- تشتغل كأنها منيو خاصة فيهم — وفيها نوعين مختلطين:
--   1) أصناف زيادة ثابتة  → مكانها جدول "أصناف يومية ثابتة" في أمر التشغيل
--   2) أصناف بديلة        → مكانها جدول "الأصناف البديلة" فوق
--
-- هذا العمود يفصل النوعين: عند تفعيله يُحتسب الصنف الثابت ضمن البدائل
-- (أو بدائل السناكات لو كان سناك) ويختفي من جدول الأصناف اليومية الثابتة.
-- إحصاء الأصناف الكلي لا يتأثر — نفس الكمية، بس تحت عنوان مختلف.
--
-- شغّله مرة واحدة في Supabase SQL Editor.
-- ============================================================================

alter table public.beneficiary_fixed_meals
  add column if not exists is_alternative boolean not null default false;
