export const CAT_FROM_AR: Record<string, ItemCategory> = { 'حار': 'hot', 'بارد': 'cold', 'سناك': 'snack' };

/** لاحقة الفئة: `@حار` / `@بارد` / `@سناك` */
export const CATEGORY_MARK_RE = new RegExp(`@\\s*(حار|بارد|سناك)${NOT_ARABIC_LETTER}`);

/** علامة «صنف بديل» على الصنف الثابت: `مكرونة؛سبت@بديل` */
export const ALT_MARK = '@بديل';
export const ALT_MARK_RE = new RegExp(`@\\s*بديل${NOT_ARABIC_LETTER}`);

