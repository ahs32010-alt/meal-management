/**
 * ⚠️ لا تستخدم `\b` بعد كلمة عربية.
 *
 * حدود الكلمة في تعابير JS معرّفة على `[A-Za-z0-9_]` فقط، والحرف العربي ليس
 * منها — فتعبير مثل `/@بارد\b/` **لا يطابق أبداً**، لا في نهاية النص ولا قبل
 * رمز آخر. كانت لاحقة الفئة تُكتب في التصدير ولا تُقرأ في الاستيراد إطلاقاً،
 * فيرجع كل صنف لفئة القسم الافتراضية بعد أي تنزيل ثم رفع.
 *
 * البديل الصحيح: نمنع فقط أن يتبعها حرف عربي (أي أن الكلمة لم تكتمل)، فتُطابق
 * «@بارد» و«@بارد↛…» ولا تُطابق «@باردة».
 */
export const NOT_ARABIC_LETTER = '(?![ء-ي])';

