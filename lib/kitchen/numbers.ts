/**
 * الأرقام بالعامية السعودية.
 *
 * ── ليش نكتبها بأنفسنا بدل تمرير «57» للمحرّك؟ ─────────────────────────────
 * لأن محرّك النطق يقرأ الرقم بالفصحى: «سبعةٌ وخمسون». وأحد لا يتكلّم كذا في
 * مطبخ. المشغّل تعوّد على أذن المشرف وهو يقول «سبعة وخمسين» — والفرق بين
 * النهايتين هو الفرق بين كلام طبيعي وكلام نشرة أخبار.
 *
 * ── أين نلتزم بالعامية وأين نتراجع ─────────────────────────────────────────
 * العشرات والمئات عامية صرفة: «سبعة وخمسين»، «مية وأربعة وأربعين». أما
 * ١١–١٩ فنكتبها بصيغتها المدرسية («أحد عشر») لا العامية («احدعش»): محرّكات
 * النطق تتعثّر في الثانية فتخرج مسخاً، والأولى يفهمها كل عربي بلا لبس.
 * والمقايضة رابحة — أرقام العشرة نادرة في أوامرك، والعشرات هي الغالبة.
 */

const ONES = ['', 'واحد', 'اثنين', 'ثلاثة', 'أربعة', 'خمسة', 'ستة', 'سبعة', 'ثمانية', 'تسعة'];

/** ١٠–١٩ — الصيغة المفهومة عند كل المحرّكات. */
const TEENS = [
  'عشرة', 'أحد عشر', 'اثنا عشر', 'ثلاثة عشر', 'أربعة عشر',
  'خمسة عشر', 'ستة عشر', 'سبعة عشر', 'ثمانية عشر', 'تسعة عشر',
];

/** العشرات بنهاية «ـين» — وهي نطق أهل نجد والحجاز، لا «ـون» الفصحى. */
const TENS = ['', '', 'عشرين', 'ثلاثين', 'أربعين', 'خمسين', 'ستين', 'سبعين', 'ثمانين', 'تسعين'];

/** المئات عامية: «مية» و«ميتين» لا «مائة» و«مئتان». */
const HUNDREDS = [
  '', 'مية', 'ميتين', 'ثلاثمية', 'أربعمية',
  'خمسمية', 'ستمية', 'سبعمية', 'ثمانمية', 'تسعمية',
];

/**
 * يحوّل عدداً إلى كلمات عامية.
 *
 * @example numberToSaudiWords(57)  // 'سبعة وخمسين'
 * @example numberToSaudiWords(144) // 'مية وأربعة وأربعين'
 */
export function numberToSaudiWords(value: number): string {
  if (!Number.isFinite(value)) return '';
  const n = Math.trunc(Math.abs(value));

  if (n === 0) return 'صفر';
  if (n < 10) return ONES[n];
  if (n < 20) return TEENS[n - 10];

  if (n < 100) {
    const tens = TENS[Math.floor(n / 10)];
    const ones = ONES[n % 10];
    // الآحاد قبل العشرات: «سبعة وخمسين» لا «خمسين وسبعة».
    return ones ? `${ones} و${tens}` : tens;
  }

  if (n < 1000) {
    const hundreds = HUNDREDS[Math.floor(n / 100)];
    const rest = n % 100;
    return rest === 0 ? hundreds : `${hundreds} و${numberToSaudiWords(rest)}`;
  }

  // فوق الألف خارج أي احتمال واقعي في أمر تشغيل — نرجّع الرقم كما هو بدل
  // اختراع صياغة لن تُسمع أبداً.
  return String(n);
}
