'use client';

/**
 * لقطة آخر بيانات عُرضت في كل صفحة — لتُرسم فوراً عند الرجوع إليها.
 *
 * المشكلة: كل صفحة كانت تبدأ فاضية بمؤشّر تحميل وتنتظر الشبكة. ومع تأخير
 * ٤٠٠–١٤٠٠ms للرحلة الواحدة، كان التنقّل بين الصفحات يبدو معلّقاً في كل مرّة
 * حتى لو كانت نفس البيانات التي عُرضت قبل ثوانٍ.
 *
 * الحل هنا **لا يمنع أي طلب ولا يؤجّله**: الصفحة ترسم آخر لقطة فوراً، والطلب
 * ينطلق كالمعتاد ويستبدل المعروض بمجرّد وصوله. فالبيانات تبقى طازجة دائماً،
 * والذي تغيّر هو أن المستخدم يرى محتوى بدل شاشة فارغة أثناء الانتظار.
 *
 * في الذاكرة فقط عمداً (لا localStorage): تُمسح مع إعادة تحميل الصفحة، فلا
 * يمكن أن تعيش لقطة قديمة بعد تسجيل خروج أو تبديل مستخدم.
 */

const store = new Map<string, unknown>();

/** آخر لقطة محفوظة لهذا المفتاح، أو null. */
export function readSnapshot<T>(key: string): T | null {
  return store.has(key) ? (store.get(key) as T) : null;
}

/** يحفظ ما عُرض للتوّ ليُرسم فوراً عند الزيارة القادمة. */
export function writeSnapshot<T>(key: string, value: T): void {
  store.set(key, value);
}

/**
 * يُسقط اللقطات. بلا وسيط يمسح كل شيء (تسجيل الخروج)، ومع بادئة يمسح ما
 * يخصّها وحدها.
 */
export function clearSnapshots(prefix?: string): void {
  if (!prefix) { store.clear(); return; }
  for (const k of store.keys()) if (k.startsWith(prefix)) store.delete(k);
}
