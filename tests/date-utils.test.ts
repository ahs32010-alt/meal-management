import { describe, expect, it } from 'vitest';
import { todayISO } from '@/lib/date-utils';

/**
 * todayISO يحدّد هل أمر التشغيل «قادم» (يُحسب حيّاً في كل مرة) أو «ماضٍ»
 * (يبقى بلقطته المجمّدة). الخادم يشتغل بتوقيت UTC، فلو اعتمدنا عليه ينزاح
 * اليوم ٣ ساعات ويطلع أمر اليوم كأنه ماضٍ بعد الساعة ٩ مساءً.
 */
describe('todayISO', () => {
  it('يرجّع التاريخ بصيغة YYYY-MM-DD', () => {
    expect(todayISO(new Date('2026-08-17T09:00:00Z'))).toBe('2026-08-17');
  });

  it('يستخدم توقيت الرياض لا توقيت الخادم', () => {
    // ٢١:٣٠ بتوقيت UTC = ٠٠:٣٠ من اليوم التالي في الرياض
    expect(todayISO(new Date('2026-08-17T21:30:00Z'))).toBe('2026-08-18');
  });

  it('ما يقفز لليوم التالي قبل منتصف ليل الرياض', () => {
    // ٢٠:٥٩ بتوقيت UTC = ٢٣:٥٩ من نفس اليوم في الرياض
    expect(todayISO(new Date('2026-08-17T20:59:00Z'))).toBe('2026-08-17');
  });

  it('المقارنة النصية تصنّف الأوامر صح (قادم مقابل ماضٍ)', () => {
    const today = todayISO(new Date('2026-08-17T09:00:00Z'));
    expect('2026-08-17' >= today).toBe(true);  // أمر اليوم → قادم
    expect('2026-09-01' >= today).toBe(true);  // أمر مستقبلي → قادم
    expect('2026-08-16' >= today).toBe(false); // أمر أمس → مجمّد
  });
});
